// Writes src/css/icons.css: the Font Awesome icons the site uses, with both fonts cut down to just those
// icons and inlined in the stylesheet. The full fonts in fa/ are about 640 KB; the cut-down ones are a
// few KB, and being inline they show at once instead of after a font download.
//
//   node tools/icons.mjs
//
// Needs fa/ (the Font Awesome icon font: fa/css/icons.css and fa/fonts/) and pyftsubset from fonttools
// (pip install fonttools brotli). fa/ stays out of git: it is the full Pro font.
//
// To use another icon, add its name (from fa/css/icons.css, without "fa-") to `icons`, run this
// again and commit src/css/icons.css. In the markup: <i class="fas fa-arrow-left" aria-hidden="true"></i>,
// where fas is the bold weight and far the regular one. Both weights get every icon in the list.
// The site uses bold for arrows, chevrons and close buttons, as it matches the label font's strokes;
// the save heart is regular (an outline) when not saved and bold (filled) when saved.

import {execFileSync} from 'node:child_process';
import {mkdtempSync, readFileSync, rmSync, writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';

const icons = [
  'arrow-left',       // back links: "← Till receptarkivet"
  'arrow-up',         // footer on the home page: "Till kylskåpet ↑"
  'arrow-up-right',   // "Visa recept ↗" and other links onward
  'camera',           // the fridge photo button on the home page
  'check',            // a recipe's ingredient once it's on the shopping list
  'chevron-down',     // the archive's category picker and the other <details> summaries
  'heart',            // save buttons
  'plus',             // a recipe's ingredient: add it to the shopping list
  'xmark'             // close and remove buttons
];

const source = new URL('../fa/', import.meta.url).pathname;
const css = readFileSync(join(source, 'css/icons.css'), 'utf8');
const codepoints = Object.fromEntries(
  [...css.matchAll(/\.fa-([a-z0-9-]+)::before\s*\{\s*content:\s*"\\([0-9a-f]+)"/g)].map(([, name, code]) => [name, code]));
const unknown = icons.filter(name => !codepoints[name]);
if (unknown.length) throw new Error(`Not in fa/css/icons.css: ${unknown.join(', ')}`);

const temp = mkdtempSync(join(tmpdir(), 'restfest-icons-'));
const subset = weight => {
  const output = join(temp, `${weight}.woff2`);
  execFileSync('pyftsubset', [
    join(source, `fonts/font-awesome-${weight}.woff2`),
    `--unicodes=${icons.map(name => `U+${codepoints[name]}`).join(',')}`,
    '--flavor=woff2', '--layout-features=', '--no-hinting', `--output-file=${output}`
  ], {stdio: ['ignore', 'ignore', 'pipe']}); // fonttools warns about the font's timestamps; harmless

  return readFileSync(output).toString('base64');
};
const fonts = {400: subset(400), 700: subset(700)};
rmSync(temp, {recursive: true});

writeFileSync(new URL('../src/css/icons.css', import.meta.url), `/* Generated by tools/icons.mjs from the Font Awesome icon font. Don't edit by hand: add the icon
   to the list in that script and run it again. Bold: fas, regular: far. */
${[400, 700].map(weight => `
@font-face {
  font-family: "Font Awesome";
  src: url(data:font/woff2;base64,${fonts[weight]}) format("woff2");
  font-weight: ${weight};
  font-display: block;
}
`).join('')}
.far, .fas {
  display: inline-block;
  flex-shrink: 0;
  font: normal normal 400 1em/1 "Font Awesome";
  color: inherit;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
}

.fas { font-weight: 700; }
${icons.map(name => `.fa-${name}::before { content: "\\${codepoints[name]}"; }`).join('\n')}
`);
console.log(`src/css/icons.css: ${icons.length} icons, ${Math.round((fonts[400].length + fonts[700].length) / 1024)} KB of font data`);
