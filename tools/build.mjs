// Builds the files the site serves from the recipe source files.
//
//   node tools/build.mjs
//
// Run it after editing recipe-collection.js or recipes.js, or the header/footer in receptarkiv.html.
// It writes:
//   data/recipe-index.js  – the small recipe list the home page and archive load (no ingredient
//                           amounts or instructions; those live on the recipe pages)
//   recept/<id>.html      – one page per recipe, with the full recipe in the HTML
//   sitemap.xml           – only when SITE_URL is set below
// No dependencies; needs Node 18 or later.

import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import {fileURLToPath} from 'node:url';

// The site's public address, e.g. 'https://restfest.se'. When set, recipe pages get canonical
// links and share images with full URLs, and sitemap.xml is written.
const SITE_URL = '';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const write = (file, content) => {
  fs.mkdirSync(path.dirname(path.join(root, file)), {recursive: true});
  fs.writeFileSync(path.join(root, file), content);
};

// Load the data the same way the browser does: as plain scripts sharing one global scope.
const context = vm.createContext({});
const run = (code, file) => vm.runInContext(code, context, {filename: file});
run(read('recipe-collection.js'), 'recipe-collection.js');
const sourceFoods = run('JSON.parse(JSON.stringify(collectionFoods))');
run(read('recipes.js'), 'recipes.js');
const {recipes, mealTypes, mealName, recipeTagLabels, allTags, isFood} =
  run('({recipes, mealTypes, mealName, recipeTagLabels, allTags, isFood})');

const escapeHtml = value => String(value).replace(/[&<>"']/g, char =>
  ({'&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;'}[char]));
const absolute = url => SITE_URL ? new URL(url, SITE_URL.replace(/\/?$/, '/')).href : null;

// ---------------------------------------------------------------- recipe index

const indexRecipes = recipes.map(recipe => ({
  id: recipe.id,
  title: recipe.title,
  description: recipe.description,
  image: recipe.image,
  cardImage: recipe.cardImage,
  meals: recipe.meals,
  tags: recipe.tags,
  time: recipe.time,
  timeLabel: recipe.timeLabel,
  pantryKeys: recipe.pantryKeys,
  foodKeys: recipe.foodKeys,
  search: recipe.search,
  ...(recipe.chips && {chips: recipe.chips}),
  ...(recipe.category && {category: recipe.category}),
  ...(recipe.swap && {swap: recipe.swap})
}));

write('data/recipe-index.js', `// Generated by tools/build.mjs from recipe-collection.js. Edit that file and run: node tools/build.mjs
'use strict';

const collectionFoods = ${JSON.stringify(sourceFoods)};

const collectionRecipes = [
${indexRecipes.map(recipe => JSON.stringify(recipe)).join(',\n')}
];
`);

// ---------------------------------------------------------------- page shell

// The header, footer and shopping list come from receptarkiv.html, so all pages stay alike.
const archive = read('receptarkiv.html');
function pick(pattern, name) {
  const match = archive.match(pattern);
  if (!match) throw new Error(`Could not find the ${name} in receptarkiv.html`);
  return match[0];
}
// Recipe pages live one folder down, so relative links and images need a "../".
const relocate = html => html
  .replace(/\b(src|href)="(?!https?:|mailto:|#|\/|\.\.\/)(?:\.\/)?([^"]*)"/g, (_, attribute, url) => `${attribute}="../${url}"`)
  .replace(' aria-current="page"', '');
const shell = {
  skipLink: pick(/<a class="skip-link"[^>]*>[^<]*<\/a>/, 'skip link'),
  header: relocate(pick(/<header class="site-header">[\s\S]*?<\/header>/, 'header')),
  footer: relocate(pick(/<footer class="site-footer">[\s\S]*?<\/footer>/, 'footer')),
  shopping: relocate(pick(/<dialog id="shopping-dialog"[\s\S]*?<\/dialog>/, 'shopping list')),
  toast: pick(/<div id="toast"[^>]*><\/div>/, 'toast'),
  sprite: pick(/<svg class="svg-sprite"[\s\S]*?<\/svg>/, 'icon sprite')
};

// ---------------------------------------------------------------- recipe page

const icon = (name, size, base) =>
  `<img src="${base}assets/icons/square/${name}.webp" alt="" width="${size}" height="${size}">`;

function renderIngredients(recipe, base) {
  return recipe.ingredientSections.map((group, groupIndex) => {
    const rows = group.items.map((item, index) => {
      if (item.note) return `<li class="ingredient-note">${escapeHtml(item.name)}</li>`;
      // Same id format as before, so shopping lists people already have keep working.
      const rowKey = `${groupIndex}-${index}-${item.key ?? 'unmatched'}`;
      const shoppingId = JSON.stringify([recipe.id, rowKey, item.name]);
      const name = escapeHtml(item.name);
      return `<li class="cook-ingredient"${item.key ? ` data-key="${item.key}"` : ''}${item.basic ? ' data-basic' : ''}>
            <label><input type="checkbox"><span>${name}</span></label>
            <div class="cook-ingredient-actions">
              <span class="ingredient-status" hidden></span>
              <button class="shopping-add" type="button" data-shopping-ingredient="${escapeHtml(shoppingId)}" data-shopping-text="${name}" aria-label="${name} på inköpslistan" aria-pressed="false">${icon('plus-sign', 16, base)}</button>
            </div>
          </li>`;
    }).join('\n          ');
    return `<div class="ingredient-group">
          ${group.title ? `<h3>${escapeHtml(group.title)}</h3>` : ''}
          <ul class="ingredients">
          ${rows}
          </ul>
        </div>`;
  }).join('\n        ');
}

function renderDirections(recipe) {
  const groups = recipe.directionGroups ?? [{start: 0}];
  return groups.map(({title, start}, index) => {
    const steps = recipe.directions.slice(start, groups[index + 1]?.start);
    return `${title ? `<h3>${escapeHtml(title)}</h3>` : ''}
        <ol class="directions">${steps.map(step => `<li>${escapeHtml(step)}</li>`).join('')}</ol>`;
  }).join('\n        ');
}

function renderRecipe(recipe, base) {
  const badge = mealTypes[recipe.meals[0]].badge;
  const mealLabels = recipe.meals.map(mealName).join(' · ');
  const noun = recipe.meals.includes('spa') ? 'behandling' : 'recept';
  const ingredientCount = recipe.ingredients.filter(item => !item.note).length;
  const facts = Object.entries(recipe.metadata).map(([label, value]) =>
    `<div><dt>${escapeHtml(label)}</dt><dd>${escapeHtml(value)}</dd></div>`).join('');
  const tags = recipe.tags.map(tag => `<li>${escapeHtml(recipeTagLabels[tag] ?? tag)}</li>`).join('');
  const srcset = recipe.cardImage
    ? ` srcset="${base}${recipe.cardImage} 600w, ${base}${recipe.image} 1200w" sizes="(min-width: 860px) 810px, 100vw"`
    : '';

  return `<article class="recipe-view" data-recipe="${recipe.id}">
    <div class="dialog-top cook-art has-photo">
      <img src="${base}${recipe.image}"${srcset} alt="${escapeHtml(recipe.alt)}" width="1200" height="675" fetchpriority="high">
    </div>
    <div class="dialog-main">
      <p class="dialog-kicker"><span class="mini-badge">RESTFEST · ${escapeHtml(badge ?? 'RECEPT')}</span>${badge ? '' : `<span>${escapeHtml(mealLabels)}</span>`}</p>
      <h1 id="recipe-title" class="recipe-heading">${escapeHtml(recipe.title)}</h1>
      <p class="dialog-intro">${escapeHtml(recipe.description)}</p>
      <dl class="recipe-facts">${facts}</dl>
      <ul class="recipe-tags" aria-label="Taggar">${tags}</ul>
      ${recipe.beforeYouStart ? `<p class="recipe-tip"><b>Bra att veta.</b> ${escapeHtml(recipe.beforeYouStart)}</p>` : ''}
      <section class="recipe-section" aria-labelledby="ingredients-heading">
        <div class="recipe-section-heading">
          <h2 id="ingredients-heading" class="cook-ingredient-heading">${icon('clipboard-2', 24, base)}Det här behöver du</h2>
          <button class="dialog-save" type="button" data-save="${recipe.id}" aria-pressed="false"><svg aria-hidden="true"><use href="#icon-heart"/></svg>Spara ${noun}</button>
        </div>
        ${recipe.pantryKeys.length ? `<div class="cook-pantry" hidden>
          <div>
            <span class="eyebrow">JÄMFÖRT MED DIN KYL</span>
            <strong class="cook-pantry-summary" role="status"></strong>
          </div>
          <button class="button cook-add-missing" type="button" hidden></button>
        </div>` : ''}
        <div class="cook-checklist">
          <progress class="cook-progress" aria-label="Avbockade råvaror" value="0" max="${ingredientCount}"></progress>
          <p class="meta cook-progress-text" aria-live="polite">0 av ${ingredientCount} avbockade</p>
        </div>
        <div class="cook-shopping">
          <p>Tryck på + vid det du behöver köpa.</p>
          <button class="text-button cook-open-shopping" type="button" aria-haspopup="dialog">${icon('shopping-basket-1', 20, base)}Inköpslista <span class="count cook-shopping-count">0</span></button>
        </div>
        <div class="cook-ingredient-columns">
        ${renderIngredients(recipe, base)}
        </div>
      </section>
      <section class="recipe-section recipe-directions" aria-labelledby="directions-heading">
        <h2 id="directions-heading">Gör så här</h2>
        ${renderDirections(recipe)}
        ${(recipe.directionNotes ?? []).map(note =>
          `<p class="recipe-tip"><b>${escapeHtml(note.title)}</b> ${escapeHtml(note.text)}</p>`).join('\n        ')}
      </section>
      ${(recipe.extraSections ?? []).map(section => `<section class="recipe-extra">
        <h2>${escapeHtml(section.title)}</h2>
        <ul>${section.items.map(item => `<li>${escapeHtml(item)}</li>`).join('')}</ul>
      </section>`).join('\n      ')}
      ${recipe.tip ? `<p class="recipe-tip"><b>Gör det till ditt.</b> ${escapeHtml(recipe.tip)}</p>` : ''}
      ${badge ? '' : `<details class="recipe-measurements">
        <summary>Mått och ugnstemperaturer</summary>
        <p>Måtten är svenska (dl, msk, tsk, krm). Ugnstemperaturerna gäller vanlig ugn med över- och undervärme; med varmluft, sänk med 20 grader.</p>
      </details>`}
    </div>
  </article>`;
}

const schemaDiets = {Vegan: 'VeganDiet', Vegetarian: 'VegetarianDiet', 'Gluten free': 'GlutenFreeDiet'};

// Recipe structured data, so search engines can show the recipe as a recipe.
function structuredData(recipe) {
  if (!isFood(recipe)) return '';
  const diets = allTags(recipe).filter(tag => tag in schemaDiets).map(tag => `https://schema.org/${schemaDiets[tag]}`);
  const data = {
    '@context': 'https://schema.org',
    '@type': 'Recipe',
    name: recipe.title,
    description: recipe.description,
    image: [absolute(recipe.image) ?? `../${recipe.image}`],
    recipeCategory: mealName(recipe.meals[0]),
    keywords: recipe.tags.map(tag => recipeTagLabels[tag] ?? tag).join(', '),
    ...(diets.length && {suitableForDiet: diets}),
    ...(recipe.metadata.Portioner && {recipeYield: recipe.metadata.Portioner}),
    ...(Number.isFinite(recipe.time) && {totalTime: `PT${recipe.time}M`}),
    recipeIngredient: recipe.ingredients.filter(item => !item.note).map(item => item.name),
    recipeInstructions: recipe.directions.map(text => ({'@type': 'HowToStep', text}))
  };
  return `\n  <script type="application/ld+json">${JSON.stringify(data).replace(/</g, '\\u003c')}</script>`;
}

function recipePage(recipe) {
  const title = escapeHtml(recipe.title);
  const description = escapeHtml(recipe.description);
  const url = absolute(`recept/${recipe.id}.html`);
  const image = absolute(recipe.image);
  return `<!doctype html>
<!-- Generated by tools/build.mjs. Edit recipe-collection.js and run: node tools/build.mjs -->
<html lang="sv" data-base="../">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="theme-color" content="#ffffff">
  <title>${title} · Restfest</title>
  <meta name="description" content="${description}">${url ? `
  <link rel="canonical" href="${url}">
  <meta property="og:url" content="${url}">` : ''}
  <meta property="og:type" content="article">
  <meta property="og:site_name" content="Restfest">
  <meta property="og:title" content="${title}">
  <meta property="og:description" content="${description}">${image ? `
  <meta property="og:image" content="${image}">
  <meta name="twitter:card" content="summary_large_image">` : ''}
  <link rel="icon" href="../assets/icons/favicon.png" type="image/png">
  <link rel="preload" href="../assets/GTMaru-Regular.woff2" as="font" type="font/woff2" crossorigin>
  <link rel="stylesheet" href="../styles.css">
  <link rel="stylesheet" href="../kitchen.css">${structuredData(recipe)}
</head>
<body>
  ${shell.skipLink}
  ${shell.header}

  <main id="main" class="wrap recipe-page">
    ${isFood(recipe)
      ? '<a class="text-button recipe-page-back" href="../receptarkiv.html"><span aria-hidden="true">←</span> Till receptarkivet</a>'
      : '<a class="text-button recipe-page-back" href="../mer-an-mat.html"><span aria-hidden="true">←</span> Till Mer än mat</a>'}
    ${renderRecipe(recipe, '../')}
  </main>

  ${shell.footer}
  ${shell.shopping}
  ${shell.toast}
  ${shell.sprite}
  <script src="../data/recipe-index.js"></script>
  <script src="../recipes.js"></script>
  <script src="../app.js"></script>
</body>
</html>
`;
}

const pageFiles = new Set();
for (const recipe of recipes) {
  const file = `${recipe.id}.html`;
  pageFiles.add(file);
  write(`recept/${file}`, recipePage(recipe));
}

// Remove pages for recipes that no longer exist.
let removed = 0;
for (const file of fs.readdirSync(path.join(root, 'recept'))) {
  if (/^[a-z0-9-]+\.html$/.test(file) && !pageFiles.has(file)) {
    fs.unlinkSync(path.join(root, 'recept', file));
    removed++;
  }
}

if (SITE_URL) {
  const urls = ['', 'receptarkiv.html', 'mer-an-mat.html', ...[...pageFiles].map(file => `recept/${file}`)];
  write('sitemap.xml', `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map(url => `  <url><loc>${escapeHtml(absolute(url))}</loc></url>`).join('\n')}
</urlset>
`);
}

const indexSize = fs.statSync(path.join(root, 'data/recipe-index.js')).size;
console.log(`data/recipe-index.js: ${recipes.length} recipes, ${Math.round(indexSize / 1024)} KB`);
console.log(`recept/: ${pageFiles.size} pages written${removed ? `, ${removed} old removed` : ''}`);
console.log(SITE_URL ? 'sitemap.xml written' : 'SITE_URL is not set: no sitemap.xml, canonical links or share images.');
